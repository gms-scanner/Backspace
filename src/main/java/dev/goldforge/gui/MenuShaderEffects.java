package dev.goldforge.gui;

/** Ten bounded, texture-free GLSL 1.20 menu effects. */
final class MenuShaderEffects {
    private MenuShaderEffects() {}
    static final String SOURCE =
            "\n"
            + "uniform int uMode;\n"
            + "vec3 palette(float x, vec3 a){return 0.5+0.5*cos(6.283185*(x+a));}\n"
            + "vec3 effect(vec2 uv,float t){\n"
            + " vec2 p=(uv-vec2(0.67,0.5))*vec2(uResolution.x/max(uResolution.y,1.0),1.0);\n"
            + " float r=length(p), a=atan(p.y,p.x); vec3 c=vec3(0.0);\n"
            + " if(uMode==1){ // Molten gold: liquid interference contours\n"
            + "  vec2 q=p; for(int i=0;i<4;i++){float f=float(i)+1.0;q+=0.12*sin(q.yx*f*2.0+t*0.23+f);}\n"
            + "  float v=sin(q.x*9.0+sin(q.y*7.0+t*0.4));\n"
            + "  c=vec3(1.0,0.58,0.09)*(0.12+0.65*pow(0.5+0.5*v,5.0));\n"
            + " }else if(uMode==2){ // Aurora curtains\n"
            + "  for(int i=0;i<7;i++){float f=float(i);float y=0.12*sin(p.x*3.0+t*0.3+f*0.3)+f*0.035-0.12;\n"
            + "   c+=exp(-abs(p.y-y)*32.0)*vec3(0.06,0.19+f*0.015,0.18+f*0.03);}\n"
            + " }else if(uMode==3){ // Soft concentric ripples\n"
            + "  float w=0.5+0.5*cos(r*43.0-t*1.7+sin(a*3.0+t*0.3));\n"
            + "  c=palette(r-t*0.025,vec3(0.1,0.3,0.5))*pow(w,8.0)*exp(-r*1.5)*0.85;\n"
            + " }else if(uMode==4){ // Orbiting luminous ribbons\n"
            + "  for(int i=0;i<5;i++){float f=float(i);float ring=0.14+f*0.075+0.025*sin(a*3.0+t*0.45+f);\n"
            + "   c+=exp(-abs(r-ring)*100.0)*palette(f*0.12+t*0.025,vec3(0.0,0.2,0.45))*0.7;}\n"
            + " }else if(uMode==5){ // Drifting jelly metaballs\n"
            + "  float v=0.0;for(int i=0;i<6;i++){float f=float(i);vec2 b=vec2(sin(t*0.23+f*2.1),cos(t*0.19+f*1.7))*0.31;\n"
            + "   v+=0.013/(dot(p-b,p-b)+0.008);}\n"
            + "  c=palette(v*0.14+t*0.02,vec3(0.05,0.32,0.6))*smoothstep(0.45,1.5,v)*0.7;\n"
            + " }else if(uMode==6){ // Woven silk waves\n"
            + "  for(int i=0;i<12;i++){float f=float(i);float y=sin(p.x*4.0+t*0.35+f*0.12)*0.2+(f-6.0)*0.025;\n"
            + "   c+=exp(-abs(p.y-y)*170.0)*palette(f*0.045,vec3(0.0,0.15,0.35))*0.42;}\n"
            + " }else if(uMode==7){ // Kaleidoscope petals\n"
            + "  float petals=abs(sin(a*6.0+t*0.22));float v=0.5+0.5*cos(r*25.0-petals*5.0-t*0.8);\n"
            + "  c=palette(r*0.7+petals*0.16+t*0.025,vec3(0.0,0.33,0.67))*pow(v,9.0)*exp(-r)*0.8;\n"
            + " }else if(uMode==8){ // Traveling neon grid\n"
            + "  vec2 q=vec2(p.x,p.y+0.13*sin(p.x*3.0+t*0.4));q.y+=t*0.035;\n"
            + "  vec2 g=abs(fract(q*12.0)-0.5);float lines=exp(-min(g.x,g.y)*65.0);\n"
            + "  c=palette(p.y*0.5+t*0.035,vec3(0.55,0.1,0.3))*lines*0.65*exp(-r*0.7);\n"
            + " }else if(uMode==9){ // Breathing eclipse and corona\n"
            + "  float radius=0.24+0.012*sin(t*0.7);float corona=exp(-abs(r-radius)*24.0);\n"
            + "  float rays=0.65+0.35*sin(a*18.0+sin(a*7.0+t*0.4)+t*0.2);\n"
            + "  c=vec3(1.0,0.43,0.08)*corona*rays+vec3(1.0,0.85,0.4)*exp(-abs(r-radius)*180.0);\n"
            + "  c*=smoothstep(radius-0.012,radius+0.003,r);\n"
            + " }else{ // Glowing spiral currents\n"
            + "  float spiral=0.5+0.5*sin(a*4.0-r*24.0+t*0.75);\n"
            + "  c=palette(r*0.6+t*0.035,vec3(0.1,0.3,0.55))*pow(spiral,12.0)*smoothstep(0.0,0.08,r)*exp(-r)*0.9;\n"
            + " }\n"
            + " // Keep the title and controls readable, independent of the selected effect.\n"
            + " c*=mix(0.07,1.0,smoothstep(0.18,0.63,uv.x));\n"
            + " c*=1.0-0.45*smoothstep(0.3,0.9,length(uv-0.5));\n"
            + " return c+vec3(0.004,0.005,0.009);\n"
            + "}\n";
}
